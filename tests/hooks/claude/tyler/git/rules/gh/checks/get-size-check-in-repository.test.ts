import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { type TestContext, test } from 'node:test';
import type { Call } from '../../../../../../../../hooks/claude/tyler/git/calls/get-calls.ts';
import {
  makeContext,
} from '../../../../../../../../hooks/claude/tyler/git/context/make-context.ts';
import {
  getSizeCheck,
} from '../../../../../../../../hooks/claude/tyler/git/rules/gh/checks/get-size-check.ts';
import { getGitEnv, runGit } from '../../../../../../../helpers/run-git.ts';
import { makeTempDir } from '../../../../../../../helpers/make-temp-dir.ts';
import { makeSizeBranch } from '../../../../../../../helpers/size/make-size-branch.ts';

const CALL: Call = {
  tool: 'gh',
  words: [
    'pr', 'create', '-d', '-t', 'feat(hooks): add a check', '-F', '/tmp/b.md', '--base', 'main',
  ].map((text) => ({ text, isOpaque: false, canSplit: false })),
  configs: [],
  assignments: [],
};

// The size check runs the real git, which must not see the hook environment that
// runs the suite (GIT_DIR and the like) or the machine's git config.
function isolateGit(t: TestContext): void {
  const saved = { ...process.env };

  for (const name of Object.keys(process.env)) {
    Reflect.deleteProperty(process.env, name);
  }

  Object.assign(process.env, getGitEnv(saved));
  t.after(() => {
    for (const name of Object.keys(process.env)) {
      Reflect.deleteProperty(process.env, name);
    }

    Object.assign(process.env, saved);
  });
}

// See makeSizeBranch: the lockfile, the file generated by the base's attributes and the
// binary file do not count; own/x.txt does, though the branch marks it generated.
const NOTE = {
  note: 'This pull request changes 456 lines, over 400. '
    + 'Reviewers lose track of a change this size; consider splitting it.',
};

test('counts the lines of a real branch for --base main, without the excluded files', (t) => {
  isolateGit(t);

  assert.deepEqual(getSizeCheck(CALL, makeContext(makeSizeBranch(t))), NOTE);
});

test('counts the files of a branch that marks everything -diff', (t) => {
  isolateGit(t);

  const repo = makeSizeBranch(t);

  writeFileSync(join(repo, '.gitattributes'), '* -diff\n');
  runGit(['commit', '--quiet', '-am', 'hide'], repo);
  runGit(['push', '--quiet'], repo);

  assert.match(JSON.stringify(getSizeCheck(CALL, makeContext(repo))), /changes \d{3} lines/);
});

test('counts the files of a repository whose config treats every file as big', (t) => {
  isolateGit(t);

  const repo = makeSizeBranch(t);

  runGit(['config', 'core.bigFileThreshold', '1'], repo);

  assert.deepEqual(getSizeCheck(CALL, makeContext(repo)), NOTE);
});

test('reads the same branch from a subdirectory of the repository', (t) => {
  isolateGit(t);

  assert.deepEqual(getSizeCheck(CALL, makeContext(join(makeSizeBranch(t), 'src'))), NOTE);
});

test('refuses outside a repository', (t) => {
  isolateGit(t);

  assert.match(
    JSON.stringify(getSizeCheck(CALL, makeContext(makeTempDir(t)))),
    /cannot measure the pull request/,
  );
});

const UNPUSHED = /push the branch first, then open the pull request"\}$/;

test('refuses a branch with a commit its upstream lacks', (t) => {
  isolateGit(t);

  const repo = makeSizeBranch(t);

  runGit(['commit', '--quiet', '--allow-empty', '-m', 'local'], repo);

  assert.match(JSON.stringify(getSizeCheck(CALL, makeContext(repo))), UNPUSHED);
});

test('refuses a branch with no upstream', (t) => {
  isolateGit(t);

  const repo = makeSizeBranch(t);

  runGit(['branch', '--unset-upstream'], repo);

  assert.match(JSON.stringify(getSizeCheck(CALL, makeContext(repo))), UNPUSHED);
});

test('refuses a detached HEAD', (t) => {
  isolateGit(t);

  const repo = makeSizeBranch(t);

  runGit(['checkout', '--quiet', '--detach'], repo);

  assert.match(JSON.stringify(getSizeCheck(CALL, makeContext(repo))), UNPUSHED);
});

test('refuses a repository whose .git/info/attributes has text', (t) => {
  isolateGit(t);

  const repo = makeSizeBranch(t);

  writeFileSync(join(repo, '.git', 'info', 'attributes'), '# local\n');

  assert.match(
    JSON.stringify(getSizeCheck(CALL, makeContext(repo))),
    /changes how git counts lines/,
  );
});
